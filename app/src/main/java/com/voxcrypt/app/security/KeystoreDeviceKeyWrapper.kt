package com.voxcrypt.app.security

import android.os.Build
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.security.keystore.StrongBoxUnavailableException
import com.voxcrypt.app.crypto.DeviceKeyWrapper
import com.voxcrypt.app.crypto.VxcException
import java.security.GeneralSecurityException
import java.security.KeyStore
import java.security.ProviderException
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Wraps per file data keys with a non exportable AES-256-GCM key stored in the
 * Android Keystore (StrongBox when the device has one). The key never leaves
 * the secure hardware / keystore daemon, which is why files protected this way
 * can only be opened on this device, by this installation of the app.
 */
class KeystoreDeviceKeyWrapper(private val alias: String = DEFAULT_ALIAS) : DeviceKeyWrapper {

    private fun keyStore(): KeyStore = KeyStore.getInstance(PROVIDER).apply { load(null) }

    fun hasKey(): Boolean = try {
        keyStore().containsAlias(alias)
    } catch (e: GeneralSecurityException) {
        false
    }

    /** True when a key exists or can be created. */
    fun isAvailable(): Boolean = try {
        getOrCreateKey()
        true
    } catch (e: Exception) {
        false
    }

    private fun existingKey(): SecretKey? = keyStore().getKey(alias, null) as? SecretKey

    @Synchronized
    private fun getOrCreateKey(): SecretKey {
        existingKey()?.let { return it }
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
            try {
                return generate(strongBox = true)
            } catch (e: StrongBoxUnavailableException) {
                // fall back to the TEE backed keystore
            } catch (e: ProviderException) {
                // some devices report StrongBox issues this way
            }
        }
        return generate(strongBox = false)
    }

    private fun generate(strongBox: Boolean): SecretKey {
        val builder = KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
        if (strongBox && Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) builder.setIsStrongBoxBacked(true)
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, PROVIDER)
        generator.init(builder.build())
        return generator.generateKey()
    }

    override fun wrap(dataKey: ByteArray, associatedData: ByteArray): ByteArray {
        try {
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey()) // IV generated by the keystore
            cipher.updateAAD(associatedData)
            val iv = cipher.iv
            if (iv.size != IV_BYTES) throw VxcException.DeviceKeyUnavailable()
            return iv + cipher.doFinal(dataKey)
        } catch (e: GeneralSecurityException) {
            throw VxcException.DeviceKeyUnavailable(e)
        } catch (e: ProviderException) {
            throw VxcException.DeviceKeyUnavailable(e)
        }
    }

    override fun unwrap(wrapped: ByteArray, associatedData: ByteArray): ByteArray {
        if (wrapped.size <= IV_BYTES + TAG_BYTES) throw VxcException.DeviceKeyUnavailable()
        try {
            val key = existingKey() ?: throw VxcException.DeviceKeyUnavailable()
            val cipher = Cipher.getInstance(TRANSFORMATION)
            cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(TAG_BYTES * 8, wrapped, 0, IV_BYTES))
            cipher.updateAAD(associatedData)
            return cipher.doFinal(wrapped, IV_BYTES, wrapped.size - IV_BYTES)
        } catch (e: GeneralSecurityException) {
            throw VxcException.DeviceKeyUnavailable(e)
        } catch (e: ProviderException) {
            throw VxcException.DeviceKeyUnavailable(e)
        }
    }

    companion object {
        const val DEFAULT_ALIAS = "voxcrypt.device.key.v1"
        private const val PROVIDER = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val IV_BYTES = 12
        private const val TAG_BYTES = 16
    }
}
